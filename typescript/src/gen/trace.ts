// Generate a trace-validation scaffold for a TLA+ spec.
//
// Spec *synthesis* (VARIABLES/Init/Next/invariants, verified with TLC) is owned by
// the Go `astdst generate` command — it has the state model and write sets and
// runs the real tools. This module deliberately does NOT re-synthesize a spec;
// it produces the one artifact the Go side does not: a TraceSpec that replays an
// NDJSON trace from the Go DST harness against an existing spec.
//
// Technique: "Validating Traces of Distributed Programs Against TLA+
// Specifications" (Cirstea/Kuppe/Loillier/Merz, SEFM 2024, arXiv:2404.16075).
// Production reference: etcd-io/raft PR #113 (NDJSON, one event per line).

import type { DstModel } from "../types";

export interface TraceSpecOptions {
  /** The spec module to EXTEND — normally the Go-generated, TLC-verified one. */
  baseModule?: string;
  /** Trace module name; default `<baseModule>Trace`. */
  traceModuleName?: string;
}

export interface TraceSpecOutput {
  module: string;
  cfg: string;
  moduleName: string;
}

function sanitize(s: string): string {
  let n = s.replace(/[^A-Za-z0-9_]/g, "_") || "Op";
  if (/^[0-9]/.test(n)) n = "_" + n;
  return n;
}

function uniqueName(base: string, used: Set<string>): string {
  let candidate = base;
  let n = 2;
  while (used.has(candidate)) candidate = `${base}_${n++}`;
  used.add(candidate);
  return candidate;
}

/**
 * Build a TraceSpec module + TLC config that replays a DST trace against
 * `baseModule`. Each operation becomes an event composed (`\cdot`) with the spec
 * action it linearizes to; `UpdateVariables` is the one TODO a human fills in to
 * map event JSON onto the spec's VARIABLES.
 */
export function generateTraceSpec(model: DstModel, opts: TraceSpecOptions = {}): TraceSpecOutput {
  const baseModule = sanitize(opts.baseModule ?? "DstSpec");
  const name = opts.traceModuleName ?? `${baseModule}Trace`;

  // Seed with the reserved names the Go synthesizer also reserves, so our
  // operation operator names line up with the base module's.
  const used = new Set<string>(["TypeOK", "Init", "Next", "Spec", "vars", "AllInvariants"]);
  const events = model.operations.map((op) => {
    const baseOp = uniqueName(sanitize(op.name), used);
    return { event: op.name, baseOp, onOp: `On${baseOp}` };
  });

  const L: string[] = [];
  const w = (s = "") => L.push(s);

  w(`---- MODULE ${name} ----`);
  w(`\\* GENERATED by ast_dst — trace-validation scaffold.`);
  w(`\\* Technique: Cirstea/Kuppe/Loillier/Merz, SEFM 2024 (arXiv:2404.16075);`);
  w(`\\* reference implementation: etcd-io/raft PR #113 (NDJSON, one event/line).`);
  w(`\\* Replays a Go DST trace against ${baseModule}. Run with:`);
  w(`\\*   TRACE_PATH=trace.ndjson tlc -config ${name}.cfg ${name}.tla`);
  w(`EXTENDS ${baseModule}, TLC, Sequences, Integers, Json, IOUtils`);
  w();
  w(`\\* The trace: newline-delimited JSON, one event per line, from $TRACE_PATH.`);
  w(`Trace == ndJsonDeserialize(IOEnv.TRACE_PATH)`);
  w();
  w(`VARIABLE l  \\* 1-based index of the next trace line to consume`);
  w();
  w(`\\* TODO: map the current trace line's fields onto the spec's VARIABLES, e.g.`);
  w(`\\*   /\\ driverBalance' = Trace[i].driverBalance`);
  w(`\\*   /\\ UNCHANGED <<...the rest...>>`);
  w(`UpdateVariables(i) == TRUE`);
  w();
  w(`\\* Consume one trace line, requiring its "event" field (when present) to`);
  w(`\\* match e, then advance.`);
  w(`IsEvent(e) ==`);
  w(`    /\\ l \\in 1..Len(Trace)`);
  w(`    /\\ ("event" \\in DOMAIN Trace[l] => Trace[l].event = e)`);
  w(`    /\\ UpdateVariables(l)`);
  w(`    /\\ l' = l + 1`);
  w();
  w(`\\* One disjunct per operation. The `+"`\\cdot`"+` (action composition) operator aligns`);
  w(`\\* one trace event with the spec action it linearizes to, even when the grain`);
  w(`\\* of atomicity differs between trace and spec.`);
  for (const e of events) {
    w(`${e.onOp} == IsEvent("${e.event}") \\cdot ${e.baseOp}`);
  }
  w();
  if (events.length) {
    w(`TraceNext ==`);
    events.forEach((e) => w(`    \\/ ${e.onOp}`));
  } else {
    w(`TraceNext == UNCHANGED <<l, vars>>`);
  }
  w();
  w(`TraceInit == l = 1 /\\ Init`);
  w(`TraceSpec == TraceInit /\\ [][TraceNext]_<<l, vars>>`);
  w();
  w(`\\* Accept iff TLC consumed exactly the whole trace (no more, no fewer steps).`);
  w(`TraceAccepted == Len(Trace) = TLCGet("stats").diameter - 1`);
  w();
  w(`====`);

  const cfg =
    [
      `\\* GENERATED by ast_dst — trace validation.`,
      `\\* Run: TRACE_PATH=trace.ndjson java -jar tla2tools.jar -config ${name}.cfg ${name}.tla`,
      `SPECIFICATION TraceSpec`,
      `INVARIANT AllInvariants`,
      `POSTCONDITION TraceAccepted`,
      `\\* TODO: bind CONSTANTS to the trace's universe (often derivable from it).`,
    ].join("\n") + "\n";

  return { module: L.join("\n") + "\n", cfg, moduleName: name };
}
