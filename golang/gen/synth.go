package gen

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/chartertrace/ast_dst/golang/extract"
)

// Draft is a synthesised TLA+ spec: the module text, the TLC config, and the
// module name (which must match the .tla filename for the tools).
type Draft struct {
	Module string
	TLA    string
	CFG    string
}

// SynthReport summarises what the deterministic synthesiser could and could not
// recover, so the result is honest about its own gaps.
type SynthReport struct {
	Variables        int `json:"variables"`        // state variables declared from the struct
	Typed            int `json:"typed"`            // variables with a precise TypeOK clause
	Operations       int `json:"operations"`       // actions emitted
	Transitions      int `json:"transitions"`      // ops with a real (non-stub) transition
	ValueTransitions int `json:"valueTransitions"` // ops with ≥1 deterministic value form (f' = …)
	StubOps          int `json:"stubOps"`          // ops left as UNCHANGED (no modellable write)
	Overrides        int `json:"overrides"`        // ops whose transition came from a config override
	ActiveInvs       int `json:"activeInvs"`       // invariant predicates active (resolve to declared vars)
	ReferenceInvs    int `json:"referenceInvs"`    // recovered predicates carried as comments (foreign vocabulary)
	StubInvs         int `json:"stubInvs"`         // invariants with no recoverable predicate
}

// maxNatDefault bounds every numeric variable to 0..MaxNat so the state space is
// finite. Small by design; raise it in the .cfg for a deeper search.
const maxNatDefault = 2

// Synthesize deterministically builds a TLA+ spec from the extracted model — no
// LLM. It declares VARIABLES + Init + TypeOK from the extracted state struct,
// turns each operation's extracted write set into a bounded transition (a written
// numeric field becomes `f' \in 0..MaxNat`, a bool `f' \in BOOLEAN`, the rest
// UNCHANGED), and fills in invariant predicates recovered verbatim from a linked
// spec. The result is SANY-parseable and TLC-checkable over a small finite state
// space.
//
// It never invents: an operation that writes no modellable field is an honest
// UNCHANGED stub; a written field of an unmodellable type (map/slice/opaque) is
// left UNCHANGED with a flagged comment rather than faked; an invariant with no
// recoverable predicate is a TODO stub excluded from AllInvariants; and a
// recovered predicate in another spec's vocabulary is a reference comment, never
// activated (so SANY stays green).
func Synthesize(m *extract.Model, moduleName string, maxNat int, overrides map[string]string) (*Draft, *SynthReport, error) {
	if moduleName == "" {
		moduleName = "DstSpec"
	}
	moduleName = sanitizeIdent(moduleName)
	if maxNat <= 0 {
		maxNat = maxNatDefault
	}

	vars := stateVars(m)
	if len(vars) == 0 {
		return nil, nil, fmt.Errorf("no state variables to model: configure state.typeName to a struct, or the named type has no fields")
	}
	varSet := make(map[string]bool, len(vars))
	byField := make(map[string]synthVar, len(vars))
	usesMaxNat := false
	for _, v := range vars {
		varSet[v.tlaName] = true
		byField[v.field] = v
		if v.kind == kindNum {
			usesMaxNat = true
		}
	}

	rep := &SynthReport{Variables: len(vars), Operations: len(m.Operations)}
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	// ---- header ---------------------------------------------------------------
	w("---- MODULE %s ----", moduleName)
	w(`\* GENERATED by ast_dst (deterministic synthesis) from %s.`, m.Source.SimPath)
	w(`\* VARIABLES/Init/TypeOK come from the extracted state struct; each operation`)
	w(`\* changes the fields its Go handler writes (bounded to keep TLC finite).`)
	w(`\* Fields of unmodellable types and unrecovered predicates are left as`)
	w(`\* flagged TODOs — never invented.`)
	w("EXTENDS Integers, Sequences, FiniteSets, TLC")
	if usesMaxNat {
		w("")
		w(`CONSTANT MaxNat  \* numeric fields are bounded to 0..MaxNat for finiteness`)
	}
	w("")

	// ---- variables ------------------------------------------------------------
	names := make([]string, len(vars))
	for i, v := range vars {
		names[i] = v.tlaName
	}
	w("VARIABLES %s", strings.Join(names, ", "))
	w("")
	w("vars == << %s >>", strings.Join(names, ", "))
	w("")

	// ---- TypeOK + Init --------------------------------------------------------
	w("TypeOK ==")
	for _, v := range vars {
		if v.typeOK != "" {
			w("    /\\ %s \\in %s", v.tlaName, v.typeOK)
			rep.Typed++
		} else {
			w(`    \* %s : %s (opaque — no precise TLA+ type)`, v.tlaName, v.goType)
		}
	}
	if rep.Typed == 0 {
		w("    /\\ TRUE")
	}
	w("")
	w("Init ==")
	for _, v := range vars {
		w("    /\\ %s = %s", v.tlaName, v.init)
	}
	w("")

	// A value transition like `clock' = clock + 1` is unbounded on its own; this
	// state constraint keeps the search finite (out-of-range successors are pruned,
	// not invariant-checked) so numeric invariants are tested over 0..MaxNat.
	if usesMaxNat {
		w("StateBound ==")
		for _, v := range vars {
			if v.kind == kindNum {
				w("    /\\ %s \\in 0..MaxNat", v.tlaName)
			}
		}
		w("")
	}

	// An override keyed to no operation is almost always a typo'd name; fail
	// loudly rather than silently ignore it (gaps render as gaps).
	if len(overrides) > 0 {
		known := map[string]bool{}
		for _, op := range m.Operations {
			known[op.Name] = true
		}
		for opName := range overrides {
			if !known[opName] {
				return nil, nil, fmt.Errorf("override for %q matches no operation (known: %s)", opName, strings.Join(opNamesOf(m), ", "))
			}
		}
	}

	// ---- operations -----------------------------------------------------------
	w(`\* Operations — %d weighted actions, transitions from extracted write sets.`, len(m.Operations))
	opNames := make([]string, 0, len(m.Operations))
	usedOps := map[string]bool{"TypeOK": true, "Init": true, "Next": true, "Spec": true, "vars": true, "AllInvariants": true}
	for _, op := range m.Operations {
		name := uniqueIdent(sanitizeIdent(op.Name), usedOps)
		opNames = append(opNames, name)
		var action string
		var real, value bool
		if ov := strings.TrimSpace(overrides[op.Name]); ov != "" {
			a, val, err := overrideAction(name, ov, vars)
			if err != nil {
				return nil, nil, err
			}
			action, real, value = a, true, val
			rep.Overrides++
		} else {
			action, real, value = opAction(name, op, vars, byField)
		}
		if real {
			rep.Transitions++
		} else {
			rep.StubOps++
		}
		if value {
			rep.ValueTransitions++
		}
		faults := ""
		if len(op.Faults) > 0 {
			faults = "; injects " + strings.Join(op.Faults, ", ")
		}
		w("")
		w(`\* weight %g (%.1f%%)%s`, op.Weight, op.Share*100, faults)
		w("%s", action)
	}
	w("")
	w("Next ==")
	if len(opNames) > 0 {
		for _, n := range opNames {
			w("    \\/ %s", n)
		}
	} else {
		w("    UNCHANGED vars")
	}
	w("")
	w("Spec == Init /\\ [][Next]_vars")
	w("")

	// ---- invariants -----------------------------------------------------------
	active := []string{"TypeOK"}
	specByName := map[string]extract.SpecInvariant{}
	for _, s := range m.Specs {
		specByName[s.Name] = s
	}
	w(`\* Invariants. A predicate is ACTIVE only if its identifiers resolve to the`)
	w(`\* declared variables above; otherwise it is carried as a reference comment.`)
	usedInv := map[string]bool{"TypeOK": true, "Init": true, "Next": true, "Spec": true, "AllInvariants": true, "vars": true}
	for _, n := range opNames {
		usedInv[n] = true
	}
	for _, inv := range m.Invariants {
		pred := recoverPredicate(inv, specByName)
		opName := uniqueIdent(sanitizeIdent(inv.Label), usedInv)
		w("")
		w(`\* %s (%s)`, inv.ID, nonEmpty(inv.SpecStatus, "no-spec"))
		switch {
		case pred == "":
			rep.StubInvs++
			w(`\* TODO: no formal predicate recovered for %s`, inv.ID)
		case predicateResolves(pred, varSet):
			rep.ActiveInvs++
			active = append(active, opName)
			w("%s ==", opName)
			w("%s", indent(pred))
		default:
			rep.ReferenceInvs++
			w(`\* reference predicate (uses state vocabulary outside this module):`)
			for _, line := range strings.Split(pred, "\n") {
				w(`\*   %s`, line)
			}
		}
	}
	w("")
	w("AllInvariants ==")
	for _, n := range active {
		w("    /\\ %s", n)
	}
	w("")
	w("====")

	// ---- TLC config -----------------------------------------------------------
	cfgLines := []string{
		`\* GENERATED by ast_dst — deterministic synthesis.`,
		"SPECIFICATION Spec",
		"INVARIANT AllInvariants",
	}
	if usesMaxNat {
		cfgLines = append(cfgLines,
			fmt.Sprintf("CONSTANT MaxNat = %d", maxNat),
			"CONSTRAINT StateBound")
	}
	cfg := strings.Join(cfgLines, "\n") + "\n"

	return &Draft{Module: moduleName, TLA: b.String(), CFG: cfg}, rep, nil
}

// opAction renders one operation as a TLA+ action from its extracted effects. A
// recovered form yields a *value* transition (`f' = f + 1`, `f' = TRUE`,
// `f' = "done"`); a written field with no recovered form falls back to a bounded
// nondeterministic update (`f' \in 0..MaxNat`); a field of an unmodellable type
// (map/slice/opaque, or a string with no literal value) is left UNCHANGED with a
// flagged comment. It returns the text, whether it is a real (non-stub)
// transition, and whether it has at least one value form (the basis for the
// "behavioral" verification claim).
func opAction(name string, op extract.Operation, vars []synthVar, byField map[string]synthVar) (text string, real, value bool) {
	effByField := map[string]extract.FieldEffect{}
	for _, e := range op.Effects {
		effByField[e.Field] = e
	}

	changed := map[string]bool{}
	var conj []string
	var unmodelled []string
	for _, f := range op.Writes {
		v, ok := byField[f]
		if !ok {
			continue
		}
		clause, isValue, modelled := fieldClause(v, effByField[f])
		if !modelled {
			unmodelled = append(unmodelled, v.tlaName)
			continue
		}
		conj = append(conj, clause)
		changed[v.tlaName] = true
		if isValue {
			value = true
		}
	}

	var sb strings.Builder
	wl := func(s string) { sb.WriteString(s + "\n") }
	for _, v := range unmodelled {
		wl(fmt.Sprintf(`\* TODO: %s changes here (type not modellable — left UNCHANGED)`, v))
	}
	if len(conj) == 0 {
		sb.WriteString(name + " == UNCHANGED vars")
		if len(unmodelled) == 0 {
			sb.WriteString("  \\* TODO: handler writes no modelled state")
		}
		return sb.String(), false, false
	}
	wl(name + " ==")
	for _, c := range conj {
		wl("    /\\ " + c)
	}
	var rest []string
	for _, v := range vars {
		if !changed[v.tlaName] {
			rest = append(rest, v.tlaName)
		}
	}
	if len(rest) > 0 {
		sb.WriteString(fmt.Sprintf("    /\\ UNCHANGED << %s >>", strings.Join(rest, ", ")))
		return sb.String(), true, value
	}
	return strings.TrimRight(sb.String(), "\n"), true, value
}

var (
	rePrimedVar  = regexp.MustCompile(`([A-Za-z_][A-Za-z0-9_]*)'`)
	reValuePrime = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*'\s*=`) // deterministic assignment f' = …
)

// overrideAction renders an operation from a config-supplied TLA+ transition — a
// hypothesis for a write the extractor couldn't recover. The override is spliced
// in verbatim and TLC is left to judge it; two guards stop it becoming a vacuous
// green: every identifier must resolve to a declared variable or known TLA+
// keyword (else the spec won't parse), and it must prime at least one declared
// variable (else it constrains no transition). UNCHANGED is filled for the rest.
func overrideAction(name, override string, vars []synthVar) (text string, value bool, err error) {
	varSet := make(map[string]bool, len(vars))
	for _, v := range vars {
		varSet[v.tlaName] = true
	}
	if !predicateResolves(override, varSet) {
		return "", false, fmt.Errorf("override for %q uses identifiers outside the module's state vocabulary (declare them as state or fix the names): %q", name, override)
	}
	primed := map[string]bool{}
	for _, m := range rePrimedVar.FindAllStringSubmatch(override, -1) {
		if varSet[m[1]] {
			primed[m[1]] = true
		}
	}
	if len(primed) == 0 {
		return "", false, fmt.Errorf("override for %q primes no declared state variable — it constrains no transition (vacuous): %q", name, override)
	}

	var sb strings.Builder
	sb.WriteString(name + " ==\n")
	sb.WriteString("    \\* override (config) — a hypothesis, verified by TLC, not recovered from code\n")
	sb.WriteString("    /\\ " + override + "\n")
	var rest []string
	for _, v := range vars {
		if !primed[v.tlaName] {
			rest = append(rest, v.tlaName)
		}
	}
	value = reValuePrime.MatchString(override)
	if len(rest) > 0 {
		sb.WriteString(fmt.Sprintf("    /\\ UNCHANGED << %s >>", strings.Join(rest, ", ")))
		return sb.String(), value, nil
	}
	return strings.TrimRight(sb.String(), "\n"), value, nil
}

// opNamesOf lists operation names, for a "no such operation" override error.
func opNamesOf(m *extract.Model) []string {
	names := make([]string, len(m.Operations))
	for i, op := range m.Operations {
		names[i] = op.Name
	}
	return names
}

// fieldClause renders the primed-variable conjunct for one written field given
// its recovered effect. It returns the clause, whether it is a deterministic
// value form, and whether the field is modellable at all.
func fieldClause(v synthVar, eff extract.FieldEffect) (clause string, value, modelled bool) {
	switch v.kind {
	case kindNum:
		switch eff.Op {
		case "inc":
			return fmt.Sprintf("%s' = %s + 1", v.tlaName, v.tlaName), true, true
		case "dec":
			return fmt.Sprintf("%s' = %s - 1", v.tlaName, v.tlaName), true, true
		case "add":
			return fmt.Sprintf("%s' = %s + %s", v.tlaName, v.tlaName, eff.Value), true, true
		case "sub":
			return fmt.Sprintf("%s' = %s - %s", v.tlaName, v.tlaName, eff.Value), true, true
		case "setNum":
			return fmt.Sprintf("%s' = %s", v.tlaName, eff.Value), true, true
		default:
			return fmt.Sprintf("%s' \\in 0..MaxNat", v.tlaName), false, true
		}
	case kindBool:
		if eff.Op == "setBool" {
			return fmt.Sprintf("%s' = %s", v.tlaName, eff.Value), true, true
		}
		return fmt.Sprintf("%s' \\in BOOLEAN", v.tlaName), false, true
	default:
		// A string field set to a literal is modellable as a value form; anything
		// else (map/slice/opaque, or a string with no literal) is left UNCHANGED.
		if v.typeOK == "STRING" && eff.Op == "setStr" {
			return fmt.Sprintf("%s' = %s", v.tlaName, eff.Value), true, true
		}
		return "", false, false
	}
}

// synthVar is one TLA+ variable derived from a Go state field.
type synthVar struct {
	tlaName string
	field   string // original Go field name (for write-set matching)
	goType  string
	init    string // concrete initial value
	typeOK  string // TLA+ set for TypeOK, or "" when no precise type
	kind    string // kindNum | kindBool | kindOther
}

const (
	kindNum   = "num"
	kindBool  = "bool"
	kindOther = "other"
)

// stateVars maps the extracted state into TLA+ variables. A struct's fields each
// become a variable; an interface (state behind a contract) cannot expose its
// fields, so it degrades to a single opaque `state` variable.
func stateVars(m *extract.Model) []synthVar {
	if m.State == nil {
		return nil
	}
	if m.State.Kind == "interface" {
		return []synthVar{{tlaName: "state", field: "state", goType: m.State.TypeName, init: "<<>>", kind: kindOther}}
	}
	used := map[string]bool{"vars": true}
	var out []synthVar
	for _, f := range m.State.Variables {
		init, typeOK, kind := tlaTypeOf(f.Type)
		out = append(out, synthVar{
			tlaName: uniqueIdent(sanitizeIdent(f.Name), used),
			field:   f.Name,
			goType:  f.Type,
			init:    init,
			typeOK:  typeOK,
			kind:    kind,
		})
	}
	return out
}

var reNumeric = regexp.MustCompile(`^(u?int(8|16|32|64)?|byte|rune|uintptr|float(32|64))$`)

// tlaTypeOf maps a Go type string to a TLA+ (initial value, TypeOK set, kind).
// Numeric fields are bounded to 0..MaxNat so the state space stays finite. An
// unknown or composite type gets a concrete initial value but no TypeOK clause,
// so the spec stays well-formed without over-claiming a type we can't model.
func tlaTypeOf(goType string) (init, typeOK, kind string) {
	t := strings.TrimSpace(goType)
	switch {
	case reNumeric.MatchString(t):
		// TypeOK uses unbounded Nat (always true); finiteness comes from the
		// StateBound CONSTRAINT, so a boundary `f' = f + 1` isn't a TypeOK violation.
		return "0", "Nat", kindNum
	case t == "bool":
		return "FALSE", "BOOLEAN", kindBool
	case t == "string":
		return `""`, "STRING", kindOther
	case strings.HasPrefix(t, "map["):
		return "<<>>", "", kindOther // empty function
	case strings.HasPrefix(t, "[]"):
		return "<<>>", "", kindOther // empty sequence
	default:
		return "<<>>", "", kindOther // opaque: parseable placeholder, no type claim
	}
}

// recoverPredicate returns the verbatim formal predicate for an invariant from a
// linked TLA+ spec, or "" when none is available. It never synthesises one.
func recoverPredicate(inv extract.Invariant, specs map[string]extract.SpecInvariant) string {
	if inv.Spec == nil {
		return ""
	}
	if s, ok := specs[inv.Spec.Name]; ok {
		return strings.TrimSpace(s.Predicate)
	}
	return ""
}

// tlaKeywords are identifiers that appear in predicates but are not state
// variables, so they don't count against a predicate "resolving".
var tlaKeywords = map[string]bool{
	"TRUE": true, "FALSE": true, "BOOLEAN": true, "STRING": true, "Int": true,
	"Nat": true, "DOMAIN": true, "SUBSET": true, "UNION": true, "CHOOSE": true,
	"IN": true, "LET": true, "ENABLED": true, "UNCHANGED": true, "Cardinality": true,
	"Len": true, "Seq": true, "Head": true, "Tail": true, "Append": true,
	"IsFiniteSet": true, "TLCGet": true, "Assert": true, "MaxNat": true,
}

var (
	reIdent       = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*`)
	reBackslashOp = regexp.MustCompile(`\\[A-Za-z]+`) // \A \E \in \cup \cdot …
	// reBinder captures the comma-separated identifier list a quantifier or
	// CHOOSE introduces, e.g. `\A a, b \in S:` or `CHOOSE x \in S:`. Those names
	// are bound locally, not foreign, so they must count as resolved.
	reBinder = regexp.MustCompile(`(?:\\(?:AA?|EE?)|\bCHOOSE\b)\s+([A-Za-z_][A-Za-z0-9_,\s]*?)\s+\\in\b`)
)

// predicateResolves reports whether every identifier in pred is a declared
// variable, a quantifier-bound variable, or a known TLA+ keyword/operator — i.e.
// the predicate is expressed over this module's state (plus its own local
// binders) and can be activated without a SANY error. It is deliberately
// conservative: any free identifier that is none of those makes the predicate
// "not resolve", so it is carried as a reference comment rather than risk a SANY
// error. Under-activating is the safe failure mode.
func predicateResolves(pred string, vars map[string]bool) bool {
	// Collect quantifier/CHOOSE binders *before* stripping backslash ops, then
	// treat them as resolved. Work on a local copy so callers' var sets are
	// untouched.
	resolved := make(map[string]bool, len(vars))
	for v := range vars {
		resolved[v] = true
	}
	for _, m := range reBinder.FindAllStringSubmatch(pred, -1) {
		for _, id := range reIdent.FindAllString(m[1], -1) {
			resolved[id] = true
		}
	}

	pred = reBackslashOp.ReplaceAllString(pred, " ")
	idents := reIdent.FindAllString(pred, -1)
	if len(idents) == 0 {
		return false
	}
	sawVar := false
	for _, id := range idents {
		if vars[id] {
			sawVar = true
			continue
		}
		if resolved[id] || tlaKeywords[id] {
			continue
		}
		return false // a free identifier that is neither a var/binder nor a keyword
	}
	return sawVar
}

// --- small TLA+ identifier helpers ----------------------------------------

func sanitizeIdent(s string) string {
	s = regexp.MustCompile(`[^A-Za-z0-9_]`).ReplaceAllString(s, "_")
	if s == "" {
		return "X"
	}
	if s[0] >= '0' && s[0] <= '9' {
		s = "_" + s
	}
	return s
}

func uniqueIdent(base string, used map[string]bool) string {
	cand := base
	for n := 2; used[cand]; n++ {
		cand = fmt.Sprintf("%s_%d", base, n)
	}
	used[cand] = true
	return cand
}

func indent(body string) string {
	lines := strings.Split(body, "\n")
	for i, l := range lines {
		if l != "" {
			lines[i] = "    " + l
		}
	}
	return strings.Join(lines, "\n")
}

func nonEmpty(s, fallback string) string {
	if s == "" {
		return fallback
	}
	return s
}
